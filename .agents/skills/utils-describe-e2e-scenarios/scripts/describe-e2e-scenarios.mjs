import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const configPath = path.join(root, 'playwrightConfig.ts');
const outputPath = path.join(root, 'context', 'foundation', 'e2e_scenarios.md');

async function filesBelow(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(entries.map(async (entry) => {
        const target = path.join(directory, entry.name);
        return entry.isDirectory() ? filesBelow(target) : [target];
    }));
    return nested.flat();
}

function matchingBrace(source, opening) {
    let depth = 0;
    for (let index = opening; index < source.length; index += 1) {
        if (source[index] === '{') depth += 1;
        if (source[index] === '}') depth -= 1;
        if (depth === 0) return index;
    }
    return source.length;
}

function mobileRanges(source) {
    const ranges = [];
    const describe = /test\.describe\s*\(\s*['\"][^'\"]*['\"]\s*,\s*\(\s*\)\s*=>\s*\{/g;
    for (const match of source.matchAll(describe)) {
        const opening = match.index + match[0].length - 1;
        const closing = matchingBrace(source, opening);
        const body = source.slice(opening, closing + 1);
        if (/test\.use\s*\([\s\S]{0,500}?\b(?:isMobile\s*:\s*true|hasTouch\s*:\s*true|deviceScaleFactor\s*:)/.test(body)) ranges.push([opening, closing]);
    }
    return ranges;
}

function scenarios(source) {
    const ranges = mobileRanges(source);
    const fileUsesMobileProfile = /^test\.use\s*\([\s\S]{0,500}?\b(?:isMobile\s*:\s*true|hasTouch\s*:\s*true|deviceScaleFactor\s*:)/m.test(source);
    const expression = /(?<![\w.])test\s*\(\s*(['\"])(.*?)\1\s*,/g;
    return [...source.matchAll(expression)].map((match) => ({
        name: match[2],
        platform: fileUsesMobileProfile || ranges.some(([start, end]) => match.index >= start && match.index <= end) ? 'mobile' : 'PC'
    }));
}

const config = await readFile(configPath, 'utf8');
const testDirMatch = config.match(/testDir\s*:\s*['\"]([^'\"]+)['\"]/);
const testMatch = config.match(/testMatch\s*:\s*\/([^/]+)\//);
if (!testDirMatch || !testMatch) throw new Error('Could not read testDir or testMatch from playwrightConfig.ts.');

const testDirectory = path.resolve(root, testDirMatch[1]);
const filePattern = new RegExp(testMatch[1]);
const testFiles = (await filesBelow(testDirectory)).filter((file) => filePattern.test(path.basename(file))).sort();
const inventory = [];
for (const file of testFiles) {
    const source = await readFile(file, 'utf8');
    for (const scenario of scenarios(source)) inventory.push({ ...scenario, file: path.relative(root, file).replaceAll('\\', '/') });
}

const rows = inventory.length === 0 ? ['| — | — | — |'] : inventory.map(({ name, file, platform }) => `| ${name.replaceAll('|', '\\|')} | \`${file}\` | ${platform} |`);
const document = `# Implemented E2E scenarios\n\nGenerated by \`utils-describe-e2e-scenarios\`. Refresh it after every Playwright E2E test change; do not edit it manually.\n\n| Scenario | Test file | Platform |\n| --- | --- | --- |\n${rows.join('\n')}\n`;
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, document, 'utf8');
console.log(`Updated ${path.relative(root, outputPath)} with ${inventory.length} scenario(s).`);
