import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import ts from 'typescript';

const GENERATOR = 'arch-make-data-logical-diag';
const OWNER = `<!-- generated by ${GENERATOR} -->`;
const STATE_PREFIX = 'src/game/state/';
const slash = value => value.replaceAll('\\', '/');

function usage(message)
{
    if (message) console.error(message);
    console.error('Usage: build-data-logical-diag.mjs [--root <dir>] [--input <file>] [--output <file>] [--check] [--force]');
    process.exit(message ? 2 : 0);
}

function argumentsOf(values)
{
    const options = {
        root: '.', input: 'context/foundation/code-graph.json',
        output: 'context/foundation/data-logical-diagram.md', check: false, force: false
    };
    while (values.length) {
        const flag = values.shift();
        if (flag === '--help') usage();
        if (flag === '--check' || flag === '--force') options[flag.slice(2)] = true;
        else if (['--root', '--input', '--output'].includes(flag) && values.length) options[flag.slice(2)] = values.shift();
        else usage(`Unknown or incomplete option: ${flag}`);
    }
    options.root = resolve(options.root);
    for (const key of ['input', 'output']) if (!isAbsolute(options[key])) options[key] = resolve(options.root, options[key]);
    return options;
}

async function readOptional(path)
{
    try { return await readFile(path, 'utf8'); }
    catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

function parseGraph(source, input, root)
{
    if (source === null) throw new Error(`Missing code graph: ${slash(relative(root, input))}.`);
    let graph;
    try { graph = JSON.parse(source); }
    catch { throw new Error(`Malformed code graph JSON: ${slash(relative(root, input))}.`); }
    if (graph?.schemaVersion !== 1 || graph?.generator !== 'arch-make-code-graph' || !Array.isArray(graph.nodes) || !Array.isArray(graph.edges)) {
        throw new Error('Malformed code graph contract. Refresh it with arch-make-code-graph.');
    }
    return graph;
}

async function filesBelow(directory)
{
    const files = [];
    async function visit(current)
    {
        let entries;
        try { entries = await readdir(current, { withFileTypes: true }); }
        catch (error) { if (error.code === 'ENOENT') return; throw error; }
        for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
            const path = join(current, entry.name);
            if (entry.isDirectory()) await visit(path);
            else if (entry.isFile() && entry.name.endsWith('.ts')) files.push(path);
        }
    }
    await visit(directory);
    return files;
}

function exported(node)
{
    return ts.canHaveModifiers(node) && (ts.getModifiers(node) ?? []).some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword);
}

function lineOf(parsed, node)
{
    return parsed.getLineAndCharacterOfPosition(node.getStart(parsed)).line + 1;
}

function parseStateSource(root, file, source)
{
    const parsed = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
    const diagnostic = parsed.parseDiagnostics?.[0];
    if (diagnostic) {
        const position = parsed.getLineAndCharacterOfPosition(diagnostic.start ?? 0);
        throw new Error(`${slash(relative(root, file))}:${position.line + 1} ${ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n')}`);
    }
    const module = slash(relative(root, file)).replace(/\.ts$/, '');
    const declarations = [];
    const imports = [];
    for (const node of parsed.statements) {
        if (ts.isImportDeclaration(node) && ts.isStringLiteralLike(node.moduleSpecifier)) imports.push({ node, specifier: node.moduleSpecifier.text });
        if (!exported(node) || !node.name || !(ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node) || ts.isClassDeclaration(node))) continue;
        const fields = [];
        if (ts.isInterfaceDeclaration(node) || ts.isClassDeclaration(node)) for (const member of node.members) {
            if (ts.isPropertySignature(member) || ts.isPropertyDeclaration(member)) {
                fields.push({
                    name: member.name?.getText(parsed) ?? '(computed)',
                    type: member.type?.getText(parsed).replace(/\s+/g, ' ') ?? 'unknown',
                    readonly: (ts.getModifiers(member) ?? []).some(modifier => modifier.kind === ts.SyntaxKind.ReadonlyKeyword),
                    optional: !!member.questionToken,
                    line: lineOf(parsed, member)
                });
            } else if (ts.isMethodSignature(member) || ts.isMethodDeclaration(member) || ts.isGetAccessor(member) || ts.isSetAccessor(member)) {
                fields.push({ name: member.name?.getText(parsed) ?? '(method)', type: 'method', readonly: false, optional: false, line: lineOf(parsed, member), method: true });
            }
        }
        declarations.push({
            id: `${module}#${node.name.text}`,
            module,
            name: node.name.text,
            kind: ts.isInterfaceDeclaration(node) ? 'interface' : ts.isTypeAliasDeclaration(node) ? 'type' : 'class',
            alias: ts.isTypeAliasDeclaration(node) ? node.type.getText(parsed).replace(/\s+/g, ' ') : null,
            fields,
            line: lineOf(parsed, node),
            file: slash(relative(root, file))
        });
    }
    return { declarations, imports, source, file: slash(relative(root, file)) };
}

async function loadStateSources(root)
{
    const parsed = [];
    for (const file of await filesBelow(join(root, 'src/game/state'))) parsed.push(parseStateSource(root, file, await readFile(file, 'utf8')));
    return parsed;
}

function reachableDeclarations(graph, declarations)
{
    const rootNodes = graph.nodes.filter(node => node.name === 'GameStateSnapshot');
    if (rootNodes.length !== 1) throw new Error('STALE_GRAPH: expected exactly one GameStateSnapshot node.');
    const byId = new Map(graph.nodes.map(node => [node.id, node]));
    const outgoing = new Map();
    for (const edge of graph.edges) {
        if (!outgoing.has(edge.from)) outgoing.set(edge.from, []);
        outgoing.get(edge.from).push(edge.to);
    }
    const reached = new Set();
    const queue = [rootNodes[0].id];
    while (queue.length) {
        const id = queue.shift();
        if (reached.has(id)) continue;
        reached.add(id);
        for (const target of outgoing.get(id) ?? []) {
            const node = byId.get(target);
            if (node?.module.startsWith(STATE_PREFIX)) queue.push(target);
        }
    }
    const declarationsById = new Map(declarations.map(item => [item.id, item]));
    return [...reached].map(id => declarationsById.get(id)).filter(Boolean).sort((a, b) => a.name.localeCompare(b.name));
}

function findingsFor(sources, allDeclarations, reached, graph)
{
    const findings = [];
    const graphStateIds = new Set(graph.nodes.filter(node => node.module.startsWith(STATE_PREFIX)).map(node => node.id));
    const sourceStateIds = new Set(allDeclarations.map(item => item.id));
    const mismatch = [...sourceStateIds].some(id => !graphStateIds.has(id)) || [...graphStateIds].some(id => !sourceStateIds.has(id));
    if (mismatch) throw new Error('STALE_GRAPH: state declarations do not match code-graph.json.');

    const reachedIds = new Set(reached.map(item => item.id));
    for (const declaration of allDeclarations) {
        const location = `${declaration.file}:${declaration.line}`;
        if (!reachedIds.has(declaration.id)) findings.push(`${location} authoritative declaration ${declaration.name} is not reachable from GameStateSnapshot.`);
        if (declaration.kind === 'class') findings.push(`${location} state declaration ${declaration.name} must not be a class.`);
        for (const field of declaration.fields) {
            const fieldLocation = `${declaration.file}:${field.line}`;
            if (field.method) findings.push(`${fieldLocation} state declaration contains behavior method ${field.name}.`);
            else if (!field.readonly) findings.push(`${fieldLocation} state field ${declaration.name}.${field.name} must be readonly.`);
            if (/\b(?:Date|Map|Set|Function|undefined|any|unknown)\b|=>/.test(field.type)) {
                findings.push(`${fieldLocation} state field ${declaration.name}.${field.name} is not JSON-safe (${field.type}).`);
            }
        }
        if (declaration.alias && /\b(?:Date|Map|Set|Function|undefined|any|unknown)\b|=>/.test(declaration.alias)) {
            findings.push(`${location} state type ${declaration.name} is not JSON-safe (${declaration.alias}).`);
        }
    }
    for (const source of sources) {
        for (const item of source.imports) if (!item.specifier.startsWith('.')) {
            findings.push(`${source.file}:${lineOf(ts.createSourceFile(source.file, source.source, ts.ScriptTarget.Latest, true), item.node)} state imports external module ${item.specifier}.`);
        }
        if (/\b(?:Phaser|window|document|localStorage|fetch)\b/.test(source.source)) findings.push(`${source.file}:1 state source contains a platform dependency.`);
    }
    const reachedGraphIds = new Set(reached.map(item => item.id));
    const nodes = new Map(graph.nodes.map(node => [node.id, node]));
    for (const edge of graph.edges) if (reachedGraphIds.has(edge.from)) {
        const target = nodes.get(edge.to);
        if (target && !target.module.startsWith(STATE_PREFIX) && target.layer !== 'asset') {
            const declaration = reached.find(item => item.id === edge.from);
            findings.push(`${declaration.file}:${declaration.line} ${declaration.name} depends on non-state declaration ${target.name}.`);
        }
    }
    return [...new Set(findings)].sort();
}

function relationshipFor(field, names)
{
    const targets = names.filter(name => new RegExp(`\\b${name}\\b`).test(field.type));
    return targets.map(target => ({
        target,
        cardinality: /\[\]|Array\s*</.test(field.type) ? '*' : field.optional || /\bnull\b/.test(field.type) ? '0..1' : '1'
    }));
}

function render(declarations, findings)
{
    const names = declarations.map(item => item.name);
    const lines = [OWNER, '', '# Logical Game State Diagram', '', 'Authoritative, persistable state reachable from `GameStateSnapshot`.', '', '## Classifications', '',
        '| Classification | Representation |', '| --- | --- |', '| Persisted | Entities in this diagram and the versioned snapshot codec |',
        '| Derived | Excluded; recomputed by pure selectors or reducers |', '| Transient | Excluded; input, Phaser objects, effects, and audio adapters |',
        '| Configuration | Excluded; static definitions and tuning |', '', '## Diagram', '', '```mermaid', 'classDiagram'];
    for (const declaration of declarations) {
        lines.push(`    class ${declaration.name} {`);
        if (declaration.alias) lines.push('        <<type>>');
        for (const field of declaration.fields.filter(item => !item.method)) {
            const mermaidType = field.type.replace(/^readonly\s+/, '').replace(/\[\]/g, 'Array')
                .replace(/\s*\|\s*/g, '_or_').replace(/[^A-Za-z0-9_<>]/g, '');
            lines.push(`        +${mermaidType} ${field.name}`);
        }
        lines.push('    }');
    }
    for (const declaration of declarations) for (const field of declaration.fields) for (const relation of relationshipFor(field, names)) {
        lines.push(`    ${declaration.name} "1" *-- "${relation.cardinality}" ${relation.target} : ${field.name}`);
    }
    lines.push('```', '', '## Entity inventory', '', '| Entity | Classification | Source |', '| --- | --- | --- |');
    for (const declaration of declarations) {
        const link = `../../${declaration.file.replaceAll(' ', '%20')}#L${declaration.line}`;
        lines.push(`| ${declaration.name} | Persisted | [${basename(declaration.file)}](${link}) |`);
    }
    lines.push('', '## Field inventory', '', '| Entity | Field | Type | Cardinality |', '| --- | --- | --- | --- |');
    for (const declaration of declarations) {
        if (declaration.alias) lines.push(`| ${declaration.name} | value | \`${declaration.alias.replaceAll('|', '\\|')}\` | 1 |`);
        for (const field of declaration.fields.filter(item => !item.method)) {
            const cardinality = /\[\]|Array\s*</.test(field.type) ? '0..*' : field.optional || /\bnull\b/.test(field.type) ? '0..1' : '1';
            lines.push(`| ${declaration.name} | ${field.name} | \`${field.type.replaceAll('|', '\\|')}\` | ${cardinality} |`);
        }
    }
    lines.push('', '## Boundary findings', '');
    if (findings.length) for (const finding of findings) lines.push(`- REFACTOR_REQUIRED ${finding}`);
    else lines.push('No findings.');
    return `${lines.join('\n')}\n`;
}

async function main()
{
    const options = argumentsOf(process.argv.slice(2));
    const graphBuilder = join(options.root, '.agents/skills/arch-make-code-graph/scripts/build-code-graph.mjs');
    const defaultInput = join(options.root, 'context/foundation/code-graph.json');
    if (options.input === defaultInput && await readOptional(graphBuilder) !== null) {
        const freshness = spawnSync(process.execPath, [graphBuilder, '--root', options.root, '--output', options.input, '--check'], {
            cwd: options.root, encoding: 'utf8', windowsHide: true
        });
        if (freshness.status !== 0) {
            const evidence = (freshness.stdout || freshness.stderr || 'code graph check failed').trim();
            throw new Error(`STALE_GRAPH: ${evidence}`);
        }
    }
    const graph = parseGraph(await readOptional(options.input), options.input, options.root);
    const sources = await loadStateSources(options.root);
    const declarations = sources.flatMap(source => source.declarations);
    const reached = reachableDeclarations(graph, declarations);
    const findings = findingsFor(sources, declarations, reached, graph);
    const expected = render(reached, findings);
    const current = await readOptional(options.output);
    if (current !== null && !current.startsWith(OWNER) && !options.force) throw new Error(`Refusing to overwrite unowned diagram: ${slash(relative(options.root, options.output))}. Use --force to replace it.`);
    if (options.check) {
        const matches = current === expected;
        console.log(`Diagram ${matches ? 'CURRENT' : 'STALE'} ${slash(relative(options.root, options.output))}; entities ${reached.length}, findings ${findings.length}`);
        if (findings.length) { console.error(`REFACTOR_REQUIRED: ${findings.length} boundary finding(s).`); process.exit(2); }
        process.exit(matches ? 0 : 1);
    }
    await mkdir(dirname(options.output), { recursive: true });
    if (current !== expected) await writeFile(options.output, expected);
    const status = current === null ? 'CREATED' : current === expected ? 'UNCHANGED' : 'UPDATED';
    console.log(`Diagram ${status} ${slash(relative(options.root, options.output))}; entities ${reached.length}, findings ${findings.length}`);
    if (findings.length) { console.error(`REFACTOR_REQUIRED: ${findings.length} boundary finding(s).`); process.exit(2); }
}

main().catch(error => {
    console.error(`${GENERATOR} failed: ${error.message}`);
    process.exit(2);
});
